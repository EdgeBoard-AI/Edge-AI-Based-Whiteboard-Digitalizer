@app.get("/api/frames")
def api_frames():
    try:
        limit = max(1, min(100, int(request.args.get("limit", 50))))
    except ValueError:
        limit = 50
    return jsonify(db.list_frames(limit))


@app.get("/api/frames/<int:frame_id>")
def api_frame(frame_id):
    frame = db.get_frame(frame_id)
    if not frame:
        return jsonify({"error": "Frame not found"}), 404
    return jsonify(frame)


@app.post("/api/process/<int:frame_id>")
def api_process(frame_id):
    try:
        result = process_frame_id(frame_id)
        return jsonify({"success": True, "result": result})
    except Exception as exc:
        db.update_processing(frame_id, error=str(exc))
        return jsonify({"success": False, "error": str(exc)}), 500


@app.get("/captures/<path:filename>")
def captured_file(filename):
    safe_name = safe_filename(filename)
    safe_path = (RECEIVED_DIR / safe_name).resolve()
    if not safe_path.exists() or not safe_path.is_file() or safe_path.parent.resolve() != RECEIVED_DIR.resolve():
        return jsonify({"error": "Capture not found"}), 404
    return send_from_directory(RECEIVED_DIR, safe_name)


@app.get("/processed/<path:filename>")
def processed_file(filename):
    safe_name = safe_filename(filename)
    safe_path = (PROCESSED_DIR / safe_name).resolve()
    if not safe_path.exists() or not safe_path.is_file() or safe_path.parent.resolve() != PROCESSED_DIR.resolve():
        return jsonify({"error": "Processed file not found"}), 404
    return send_from_directory(PROCESSED_DIR, safe_name)


def _background_process(frame_id: int):
    try:
        process_frame_id(frame_id)
    except Exception as exc:
        db.update_processing(frame_id, error=f"Image processing failed: {exc}")
        print(f"[PROCESSING ERROR] frame={frame_id}: {exc}")


@app.get("/snapshot")
def snapshot():
    latest = db.list_frames(1)
    if not latest:
        return jsonify({"error": "No frame available"}), 404
    return send_from_directory(RECEIVED_DIR, safe_filename(latest[0]["filename"]))


@app.post("/upload")
def upload():
    data = request.get_data()
    if not data:
        return jsonify({"success": False, "message": "No image received"}), 400
    if len(data) > MAX_UPLOAD_MB * 1024 * 1024:
        return jsonify({"success": False, "message": "Image too large"}), 413

    try:
        with Image.open(io.BytesIO(data)) as img:
            img.verify()
        with Image.open(io.BytesIO(data)) as img:
            img.load()
            if img.format != "JPEG":
                raise ValueError("Uploaded file is not a JPEG image")
    except Exception as exc:
        return jsonify({"success": False, "message": f"Invalid or unreadable JPEG: {exc}"}), 400

    from datetime import datetime, timezone
    filename = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S_%f") + ".jpg"
    path = RECEIVED_DIR / filename
    path.write_bytes(data)

    frame_id = db.insert_frame(filename, len(data), request.headers)
    executor.submit(_background_process, frame_id)

    return jsonify({
        "success": True,
        "status": "accepted",
        "filename": filename,
        "frame_id": frame_id,
        "processing_error": "",
    }), 202


