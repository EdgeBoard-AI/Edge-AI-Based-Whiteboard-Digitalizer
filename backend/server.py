from __future__ import annotations

import io
import os
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from flask import Flask, jsonify, render_template, request, send_from_directory
from PIL import Image

import db
from ai.pipeline import process_image
from config import CAPTURES_DIR, HOST, MAX_UPLOAD_MB, PORT, PROCESSED_DIR, RECEIVED_DIR

app = Flask(__name__)
app.config["MAX_CONTENT_LENGTH"] = MAX_UPLOAD_MB * 1024 * 1024


@app.after_request
def add_cors_headers(response):
    response.headers["Access-Control-Allow-Origin"] = "*"
    response.headers["Access-Control-Allow-Methods"] = "GET, POST, OPTIONS"
    response.headers["Access-Control-Allow-Headers"] = "*"
    return response

db.init_db()
executor = ThreadPoolExecutor(max_workers=2)


def safe_filename(filename: str) -> str:
    # Upload names are generated by the server; this also protects manual endpoints.
    clean = Path(filename or "").name.replace("..", "_")
    clean = clean.replace("\\", "/")
    return clean.split("/")[-1]


def process_frame_id(frame_id: int):
    frame = db.get_frame(frame_id)
    if not frame:
        raise ValueError("Frame not found")
    path = RECEIVED_DIR / safe_filename(frame["filename"])
    if not path.exists():
        raise FileNotFoundError(f"Missing capture file: {path.name}")
    result = process_image(path)
    db.update_processing(frame_id, result=result)
    return result


