@app.post("/reprocess")
def reprocess_alias():
    frame_id = request.form.get("id") or request.get_json(silent=True, force=False) or {}
    if isinstance(frame_id, dict):
        frame_id = frame_id.get("id")
    try:
        frame_id = int(frame_id)
    except (TypeError, ValueError):
        return jsonify({"success": False, "error": "Missing or invalid frame id"}), 400
    try:
        result = process_frame_id(frame_id)
        return jsonify({"success": True, "result": result})
    except Exception as exc:
        db.update_processing(frame_id, error=str(exc))
        return jsonify({"success": False, "error": str(exc)}), 500


@app.post("/api/reprocess-all")
def reprocess_all():
    frames = db.list_frames(1000)
    completed = failed = 0
    for frame in frames:
        try:
            process_frame_id(frame["id"])
            completed += 1
        except Exception as exc:
            db.update_processing(frame["id"], error=str(exc))
            failed += 1
    return jsonify({"success": True, "completed": completed, "failed": failed})


