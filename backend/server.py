@app.get("/health")
def health():
    from config import TESSERACT_AVAILABLE, TESSERACT_VERSION, ENABLE_OLLAMA
    frames = db.list_frames(1000)
    accepted = sum(1 for frame in frames if frame.get("processing_status") == "complete")
    rejected = sum(1 for frame in frames if frame.get("processing_status") in {"failed", "no_text", "low_confidence", "missing_tesseract"})
    return jsonify({
        "ok": True,
        "service": "EdgeBoard AI",
        "port": PORT,
        "tesseract_available": TESSERACT_AVAILABLE,
        "tesseract_version": TESSERACT_VERSION or "unavailable",
        "ollama_enabled": ENABLE_OLLAMA,
        "capture_count": len(frames),
        "accepted_count": accepted,
        "rejected_count": rejected,
    })


